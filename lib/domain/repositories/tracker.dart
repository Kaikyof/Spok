/// Комментарий задачи трекера: кто, когда и что написал.
typedef TrackerComment = ({String author, DateTime createdAt, String text});

/// Контракт трекера задач. Ядро обращается к трекеру только через него:
/// имя системы, адрес задачи, статусы по списку, комментарии, доступность.
/// Конкретная система (пока одна — Redmine) реализует контракт в слое
/// данных; выбор адаптера — по улике в спеке.
///
/// Идентификатор задачи пока `int`: строковый `IssueRef` и категории
/// статусов вводятся вместе со вторым адаптером, чтобы не переделывать
/// контракт дважды.
abstract class Tracker {
  /// Имя системы для текстов интерфейса: «Redmine», «Jira».
  String get name;

  /// Ключи `.env`, без которых трекер не спросить. Экран по ним предлагает
  /// поле для ввода, не отправляя человека в форму ключей за одним
  /// значением.
  List<String> get credentialKeys;

  /// Доступ настроен на этой машине: адрес и ключ заполнены. Нет —
  /// трекер не опрашивается, а экран объясняет, какого ключа нет.
  bool get configured;

  /// Адрес задачи для ссылки; null — адрес системы не задан.
  String? issueUrl(int issueId);

  /// id задачи → имя статуса, как его называет трекер.
  Future<Map<int, String>> statuses(List<int> issueIds);

  /// Лента комментариев задачи, новые сверху.
  Future<List<TrackerComment>> comments(int issueId);

  /// Проверка доступности; возвращает время ответа в мс.
  Future<int> ping();
}
